#!/usr/bin/env node
'use strict';

// Local build step - run with plain `node`, not part of the DCP job.
const fs = require('fs');
const path = require('path');

const wasmPath = path.join(__dirname, 'dcp-transcode.wasm');
const outPath = path.join(__dirname, 'wasm-bytes.js');

const wasmBuffer = fs.readFileSync(wasmPath);
const base64 = wasmBuffer.toString('base64');

const contents = `'use strict';\n\n/* generated by generate-wasm-base64.js from dcp-transcode.wasm - do not edit by hand */\nmodule.exports = ${JSON.stringify(base64)};\n`;

fs.writeFileSync(outPath, contents);
console.log(`Wrote ${outPath} (${base64.length} base64 chars, ${wasmBuffer.length} raw wasm bytes)`);
